function attribute(
  key: string,
  name: string,
  value: string,
  label: string,
  unit: string | null = null,
): ProductAttribute {
  return { key, name, value, label, unit };
}
function attributesFor(categoryIndex: number, itemIndex: number, item: Item): ProductAttribute[] {
  const common = [attribute("care", "Уход", "gentle", "Бережный уход")];
  const aromas = [
    "woody",
    "fresh",
    "fresh",
    "spicy",
    "floral",
    "unscented",
    "citrus",
    "woody",
    "unscented",
    "fresh",
    "floral",
    "spicy",
  ];
  const aromaNames: Record<string, string> = {
    woody: "Древесный",
    fresh: "Свежий",
    spicy: "Пряный",
    floral: "Цветочный",
    unscented: "Без отдушки",
    citrus: "Цитрусовый",
  };
  const aroma = aromas[itemIndex] ?? "fresh";
  if (categoryIndex <= 1) {
    common.push(attribute("aroma", "Аромат", aroma, aromaNames[aroma] ?? aroma));
    const volume = [200, 250, 150][itemIndex % 3] ?? 200;
    common.push(attribute("volume", "Объём", String(volume), `${volume} мл`, "мл"));
    if (categoryIndex === 0) {
      const hours = [40, 50, 30][itemIndex % 3] ?? 40;
      common.push(attribute("burn-time", "Время горения", String(hours), `${hours} часов`, "ч"));
      common.push(
        attribute(
          "wick",
          "Фитиль",
          itemIndex % 2 ? "wood" : "cotton",
          itemIndex % 2 ? "Деревянный" : "Хлопковый",
        ),
      );
    } else {
      common.push(
        attribute(
          "duration",
          "Срок использования",
          itemIndex % 2 ? "8" : "12",
          itemIndex % 2 ? "До 8 недель" : "До 12 недель",
          "нед.",
        ),
      );
    }
  } else if (categoryIndex === 2 || categoryIndex === 4) {
    const washable = ["porcelain", "glass", "steel", "stoneware"].includes(item[4]);
    common.push(
      attribute(
        "dishwasher-safe",
        "Посудомоечная машина",
        washable ? "yes" : "no",
        washable ? "Можно мыть" : "Только ручная мойка",
      ),
    );
    const size = ["small", "medium", "large"][itemIndex % 3] ?? "medium";
    common.push(
      attribute(
        "size",
        "Размер",
        size,
        size === "small" ? "Компактный" : size === "large" ? "Большой" : "Средний",
      ),
    );
    if (categoryIndex === 2 && ["mug", "bowl", "jug"].includes(item[5]))
      common.push(attribute("volume", "Объём", "350", "350 мл", "мл"));
  } else if (categoryIndex === 3) {
    const dimensions =
      item[5] === "throw"
        ? "130x180"
        : item[5] === "cushion"
          ? "45x45"
          : item[5] === "tablecloth"
            ? "150x220"
            : item[5] === "towel"
              ? "70x140"
              : "40x40";
    common.push(
      attribute("size", "Размер", dimensions, `${dimensions.replace("x", " × ")} см`, "см"),
    );
    common.push(
      attribute(
        "pattern",
        "Рисунок",
        itemIndex % 3 === 1 ? "striped" : "plain",
        itemIndex % 3 === 1 ? "Полоска" : "Однотонный",
      ),
    );
  } else {
    const height = [18, 24, 30][itemIndex % 3] ?? 18;
    common.push(attribute("height", "Высота", String(height), `${height} см`, "см"));
    common.push(
      attribute(
        "finish",
        "Поверхность",
        itemIndex % 2 ? "smooth" : "textured",
        itemIndex % 2 ? "Гладкая" : "Фактурная",
      ),
    );
  }
  return common;
}

export const seedProducts = collections.flatMap((items, categoryIndex) =>
  items.map((item, itemIndex) => {
    const category = seedCategories[categoryIndex];
    const brand =
      seedBrands[
        categoryIndex === 3
          ? itemIndex % 2
            ? 3
            : 1
          : (categoryIndex + itemIndex) % seedBrands.length
      ];
    if (!category || !brand) throw new Error("Invalid seed category or brand");
    const [slug, name, price, colorKey, materialKey, typeKey, detail] = item;
    const product: Product = {
      id: identifier(1000 + categoryIndex * 100 + itemIndex),
      slug,
      sku: `TH-${category.slug.slice(0, 3).toUpperCase()}-${String(itemIndex + 1).padStart(3, "0")}`,
      name,
      price,
      currency: "RUB",
      category,
      brand,
      color: colors[colorKey],
      material: { slug: materialKey, name: materials[materialKey] },
      type: { slug: typeKey, name: types[typeKey] },
      shortDescription: detail,
      description: `${detail} ${brand.name} выбирает сдержанные формы и приятные тактильные поверхности. ${materials[materialKey]} и ${colors[colorKey].name.toLowerCase()} оттенок легко сочетаются с натуральным деревом, льном и любимыми домашними вещами. Подойдёт для собственного дома или небольшого подарка.`,
      availability: itemIndex === 5 || itemIndex === 10 ? "out_of_stock" : "in_stock",
      featured: itemIndex === 0 || itemIndex === 1,
      createdAt: new Date(Date.UTC(2026, 8, 1 + itemIndex + categoryIndex)).toISOString(),
      images: [],
      attributes: attributesFor(categoryIndex, itemIndex, item),
    };
    const searchText = normalizeSearch(
      [
        name,
        detail,
        product.description,
        brand.name,
        brand.slug,
        category.name,
        category.slug,
        product.color.name,
        product.material.name,
        product.type.name,
        ...product.attributes.flatMap((entry) => [entry.name, entry.label, entry.value]),
      ].join(" "),
    );
    return { product, searchText, popularity: 100 - itemIndex * 3 - categoryIndex };
  }),
);
